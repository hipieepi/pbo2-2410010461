    private void saring() {
        String kata = cariField.getText().trim();

        if (kata.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            sorter.setRowFilter(
                RowFilter.regexFilter(
                    "(?i)" + Pattern.quote(kata), 0, 1, 2
                )
            );
        }

        perbaruiStatus();
    }
    
    /**
    * Mengubah nomor baris tampilan menjadi nomor baris model,
    * karena tabel dapat diurutkan dan disaring.
    */
    private int barisTerpilih() {
        int barisTampilan = bukuTable.getSelectedRow();

        if (barisTampilan < 0) {
            return -1;
        }

        return bukuTable.convertRowIndexToModel(barisTampilan);
    }
    
    private void tambah() {
        Buku baru = new FormBuku(
            this, "Tambah Buku", null
        ).tampilkan();

        if (baru != null) {
            model.tambah(baru);
            perbaruiStatus();
        }
    }
    
    private void ubah() {
        int baris = barisTerpilih();

        if (baris < 0) {
            return;
        }

        Buku hasil = new FormBuku(
            this,
            "Ubah Buku",
            model.get(baris)
        ).tampilkan();

        if (hasil != null) {
            model.ubah(baris, hasil);
            perbaruiStatus();
        }
    }
    
    private void hapus() {
        int baris = barisTerpilih();

        if (baris < 0) {
            return;
        }

        String judul = model.get(baris).judul();

        int jawab = JOptionPane.showConfirmDialog(
            this,
            "Hapus buku " + judul + "?",
            "Konfirmasi Hapus",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );

        if (jawab == JOptionPane.YES_OPTION) {
            model.hapus(baris);
            perbaruiStatus();
        }
    }
    
    private void perbaruiTombol() {
        boolean adaPilihan = bukuTable.getSelectedRow() >= 0;

        editButton.setEnabled(adaPilihan);
        hapusButton.setEnabled(adaPilihan);

        editItem.setEnabled(adaPilihan);
        hapusItem.setEnabled(adaPilihan);
    }
    
    private void perbaruiStatus() {
        int jumlahBuku = bukuTable.getRowCount();
        int jumlahTotal = model.getRowCount();
        int jumlahTersedia = 0;

        for (int i = 0; i < model.getRowCount(); i++) {
            if (model.get(i).status() == StatusBuku.TERSEDIA) {
                jumlahTersedia++;
            }
        }

        jumlahLabel.setText(
            "Menampilkan " + jumlahBuku +
            " dari " + jumlahTotal + " buku"
        );

        tersediaLabel.setText(
            "Buku tersedia: " + jumlahTersedia
        );
    }
