    private void simpan() {
        String kode = kodeField.getText().trim();
        String judul = judulField.getText().trim();
        String penulis = penulisField.getText().trim();
        String teksTahun = tahunTerbitField.getText().trim();

        // Validasi kode dan judul.
        if (kode.isEmpty() || judul.isEmpty()) {
            pesanLabel.setText("Kode dan judul wajib diisi.");
            return;
        }

        // Validasi tahun harus berupa angka.
        int tahun;

        try {
            tahun = Integer.parseInt(teksTahun);
        } catch (NumberFormatException e) {
            pesanLabel.setText("Tahun harus berupa angka.");
            return;
        }

        // Validasi rentang tahun.
        int tahunSekarang = Year.now().getValue();

        if (tahun < 1900 || tahun > tahunSekarang) {
            pesanLabel.setText(
                "Tahun harus antara 1900 dan " + tahunSekarang
            );
            return;
        }

        StatusBuku status = (StatusBuku) statusBukuCombo.getSelectedItem();

        hasil = new Buku(kode, judul, penulis, tahun, status);

        dispose();
    }
    public Buku tampilkan() {
        setVisible(true);
        return hasil;
    }
